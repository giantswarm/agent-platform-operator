#!/usr/bin/env bash
# Writes the CustomResourceDefinitions the envtest suite installs into
# OUT_DIR, from the pinned kagent-crds and substrate-crds charts and the
# pinned Flux release.
#
# Usage: hack/fetch-envtest-crds.sh OUT_DIR KAGENT_CRDS_VERSION SUBSTRATE_CRDS_VERSION FLUX_VERSION
set -euo pipefail

if [[ $# -ne 4 ]]; then
	echo "usage: $0 OUT_DIR KAGENT_CRDS_VERSION SUBSTRATE_CRDS_VERSION FLUX_VERSION" >&2
	exit 2
fi
out_dir=$1
kagent_version=$2
substrate_version=$3
flux_version=$4

for bin in helm yq curl tar; do
	command -v "$bin" >/dev/null || { echo "$bin is required" >&2; exit 1; }
done

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

header() {
	printf '# Generated by `make envtest-crds` from %s. Do not edit.\n' "$1"
}

crds_only() {
	yq eval-all 'select(.kind == "CustomResourceDefinition")' "$@"
}

chart_crds() {
	local repo=$1 chart=$2 version=$3 target=$4
	helm pull "oci://gsoci.azurecr.io/giantswarm/${repo}/helm/${chart}" --version "$version" --destination "$work" >/dev/null
	{
		header "oci://gsoci.azurecr.io/giantswarm/${repo}/helm/${chart}:${version}"
		helm template "$chart" "$work/${chart}-${version}.tgz" | crds_only -
	} >"$target"
}

mkdir -p "$out_dir"
chart_crds kagent kagent-crds "$kagent_version" "$out_dir/kagent.yaml"
chart_crds substrate substrate-crds "$substrate_version" "$out_dir/substrate.yaml"

mkdir -p "$work/flux"
curl -fsSL --retry 3 "https://github.com/fluxcd/flux2/releases/download/${flux_version}/manifests.tar.gz" | tar xz -C "$work/flux"
{
	header "github.com/fluxcd/flux2 ${flux_version} (source-controller, kustomize-controller, helm-controller)"
	crds_only "$work/flux/source-controller.yaml" "$work/flux/kustomize-controller.yaml" "$work/flux/helm-controller.yaml"
} >"$out_dir/flux.yaml"
